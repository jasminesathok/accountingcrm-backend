const PDFDocument = require('pdfkit');

const fmt = (n) => Number(n || 0).toFixed(2);

// Streams an A/R Aging report as a PDF onto the given writable stream (an
// Express response, in normal use). Kept separate from reportService so the
// report data itself stays a plain JSON-serializable object usable by both
// the JSON endpoint and this export.
function writeARAgingPdf(reportData, stream) {
  const doc = new PDFDocument({ margin: 40, size: 'A4', layout: 'landscape' });
  doc.pipe(stream);

  const { report, summary, details, generatedBy, generatedDate } = reportData;

  doc.fontSize(16).text('Accounting CRM', { align: 'center' });
  doc.fontSize(13).text('Accounts Receivable Aging', { align: 'center' });
  doc.moveDown(0.5);

  doc.fontSize(9).fillColor('#444');
  const metaLine = [
    report.reportId ? `Report ID: ${report.reportId}` : null,
    report.asOnDate ? `As On Date: ${report.asOnDate}` : null,
    `Currency: ${report.currency || 'INR'}`,
    `Status: ${report.reportStatus || 'Generated'}`
  ].filter(Boolean).join('   |   ');
  doc.text(metaLine, { align: 'center' });
  doc.moveDown(1);
  doc.fillColor('#000');

  const colWidths = [95, 65, 65, 65, 65, 65, 65, 60, 90];
  const headers = ['Client', 'Invoice #', 'Invoice Date', 'Due Date', 'Invoice Amt', 'Paid', 'Outstanding', 'Days', 'Bucket'];
  let y = doc.y;
  const startX = doc.page.margins.left;

  const drawRow = (cells, opts = {}) => {
    let x = startX;
    doc.fontSize(opts.fontSize || 8).font(opts.bold ? 'Helvetica-Bold' : 'Helvetica');
    cells.forEach((cell, i) => {
      doc.text(String(cell), x, y, { width: colWidths[i], align: i <= 0 || i === 8 ? 'left' : 'right' });
      x += colWidths[i];
    });
    y += 16;
  };

  drawRow(headers, { bold: true });
  doc.moveTo(startX, y).lineTo(startX + colWidths.reduce((a, b) => a + b, 0), y).stroke();
  y += 4;

  (details || []).forEach((row) => {
    if (y > doc.page.height - doc.page.margins.bottom - 40) {
      doc.addPage({ margin: 40, size: 'A4', layout: 'landscape' });
      y = doc.page.margins.top;
    }
    drawRow([
      row.clientName, row.invoiceNumber,
      row.invoiceDate || '-', row.dueDate || '-',
      fmt(row.invoiceAmount), fmt(row.amountPaid), fmt(row.outstandingAmount),
      row.daysOverdue, row.bucket
    ]);
  });

  y += 6;
  doc.moveTo(startX, y).lineTo(startX + colWidths.reduce((a, b) => a + b, 0), y).stroke();
  y += 8;

  doc.fontSize(9).font('Helvetica-Bold').text(
    `Current: ${fmt(summary.current)}   |   1-30: ${fmt(summary['1-30'])}   |   31-60: ${fmt(summary['31-60'])}   |   61-90: ${fmt(summary['61-90'])}   |   91-120: ${fmt(summary['91-120'])}   |   Above 120: ${fmt(summary.above120)}`,
    startX, y
  );
  y += 18;
  doc.text(
    `Total Outstanding: ${fmt(summary.totalOutstanding)}   |   Total Overdue: ${fmt(summary.totalOverdue)}   |   Total Customers: ${summary.totalCustomers}` +
    (summary.averageCollectionDays !== null && summary.averageCollectionDays !== undefined ? `   |   Avg Collection Days: ${summary.averageCollectionDays}` : ''),
    startX, y
  );

  y += 30;
  doc.fontSize(8).font('Helvetica').fillColor('#666').text(
    `Generated By: ${generatedBy || '—'}   |   Generated Date: ${generatedDate ? new Date(generatedDate).toLocaleString() : '—'}`,
    startX, y
  );

  doc.end();
}

// Same PDF, collected into a Buffer instead of streamed — used for the
// email attachment (Email Report), where we need the bytes up front rather
// than piping straight to an HTTP response.
function arAgingPdfBuffer(reportData) {
  const { PassThrough } = require('stream');
  return new Promise((resolve, reject) => {
    const stream = new PassThrough();
    const chunks = [];
    stream.on('data', (chunk) => chunks.push(chunk));
    stream.on('end', () => resolve(Buffer.concat(chunks)));
    stream.on('error', reject);
    writeARAgingPdf(reportData, stream);
  });
}

module.exports = { writeARAgingPdf, arAgingPdfBuffer };
