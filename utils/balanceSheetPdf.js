const PDFDocument = require('pdfkit');

const fmt = (n) => Number(n || 0).toFixed(2);

// Streams a Balance Sheet report as a PDF onto the given writable stream
// (an Express response, in normal use). Kept separate from reportService so
// the report data itself stays a plain JSON-serializable object usable by
// both the JSON endpoint and this export.
function writeBalanceSheetPdf(reportData, stream) {
  const doc = new PDFDocument({ margin: 40, size: 'A4' });
  doc.pipe(stream);

  const { report, assets, liabilities, equity, balanceSummary, generatedBy, generatedDate } = reportData;

  doc.fontSize(16).text('Accounting CRM', { align: 'center' });
  doc.fontSize(13).text('Balance Sheet', { align: 'center' });
  doc.moveDown(0.5);

  doc.fontSize(9).fillColor('#444');
  const metaLine = [
    report.reportId ? `Report ID: ${report.reportId}` : null,
    report.financialYear ? `Financial Year: ${report.financialYear}` : null,
    report.reportPeriod ? `Period: ${report.reportPeriod}` : null,
    report.asOnDate ? `As On: ${report.asOnDate}` : null,
    `Currency: ${report.currency || 'INR'}`,
    `Status: ${report.reportStatus || 'Generated'}`
  ].filter(Boolean).join('   |   ');
  doc.text(metaLine, { align: 'center' });
  doc.moveDown(1);
  doc.fillColor('#000');

  const startX = doc.page.margins.left;
  const labelWidth = 260;
  const valueWidth = 140;

  const drawSectionTitle = (title) => {
    doc.moveDown(0.5);
    doc.fontSize(11).font('Helvetica-Bold').text(title, startX, doc.y);
    doc.moveDown(0.2);
  };

  const drawLine = (label, value, opts = {}) => {
    const y = doc.y;
    doc.fontSize(opts.bold ? 10 : 9).font(opts.bold ? 'Helvetica-Bold' : 'Helvetica');
    doc.text(label, startX, y, { width: labelWidth });
    doc.text(fmt(value), startX + labelWidth, y, { width: valueWidth, align: 'right' });
    doc.moveDown(0.35);
  };

  drawSectionTitle('Assets');
  drawLine('Cash in Hand', assets.cashInHand);
  drawLine('Bank Balance', assets.bankBalance);
  drawLine('Accounts Receivable', assets.accountsReceivable);
  drawLine('Inventory', assets.inventory);
  drawLine('Prepaid Expenses', assets.prepaidExpenses);
  drawLine('Other Assets', assets.otherAssets);
  drawLine('Total Current Assets', assets.totalCurrentAssets, { bold: true });
  drawLine('Fixed Assets', assets.fixedAssets);
  drawLine('Investments', assets.investments);
  drawLine('Total Non-Current Assets', assets.totalNonCurrentAssets, { bold: true });
  drawLine('Total Assets', assets.totalAssets, { bold: true });

  drawSectionTitle('Liabilities');
  drawLine('Accounts Payable', liabilities.accountsPayable);
  drawLine('Short-Term Loans', liabilities.shortTermLoans);
  drawLine('Taxes Payable', liabilities.taxesPayable);
  drawLine('Accrued Expenses', liabilities.accruedExpenses);
  drawLine('Other Liabilities', liabilities.otherLiabilities);
  drawLine('Total Current Liabilities', liabilities.totalCurrentLiabilities, { bold: true });
  drawLine('Long-Term Loans', liabilities.longTermLoans);
  drawLine('Total Non-Current Liabilities', liabilities.totalNonCurrentLiabilities, { bold: true });
  drawLine('Total Liabilities', liabilities.totalLiabilities, { bold: true });

  drawSectionTitle('Equity');
  drawLine("Owner's Capital", equity.ownersCapital);
  drawLine('Retained Earnings', equity.retainedEarnings);
  drawLine('Current Year Profit/Loss', equity.currentYearProfitLoss);
  drawLine('Drawings', equity.drawings);
  drawLine('Total Equity', equity.totalEquity, { bold: true });

  drawSectionTitle('Balance Summary');
  drawLine('Total Assets', balanceSummary.totalAssets, { bold: true });
  drawLine('Total Liabilities', balanceSummary.totalLiabilities, { bold: true });
  drawLine('Total Equity', balanceSummary.totalEquity, { bold: true });
  drawLine('Total Liabilities & Equity', balanceSummary.totalLiabilitiesAndEquity, { bold: true });

  doc.moveDown(0.3);
  doc.fontSize(10).font('Helvetica-Bold').text(`Balance Status: ${balanceSummary.balanceStatus}`, startX, doc.y);

  doc.moveDown(1.5);
  doc.fontSize(8).font('Helvetica').fillColor('#666').text(
    `Generated By: ${generatedBy || '—'}   |   Generated Date: ${generatedDate ? new Date(generatedDate).toLocaleString() : '—'}`,
    startX, doc.y
  );

  doc.end();
}

// Same PDF, collected into a Buffer instead of streamed — used for the
// email attachment (Email Report), where we need the bytes up front rather
// than piping straight to an HTTP response.
function balanceSheetPdfBuffer(reportData) {
  const { PassThrough } = require('stream');
  return new Promise((resolve, reject) => {
    const stream = new PassThrough();
    const chunks = [];
    stream.on('data', (chunk) => chunks.push(chunk));
    stream.on('end', () => resolve(Buffer.concat(chunks)));
    stream.on('error', reject);
    writeBalanceSheetPdf(reportData, stream);
  });
}

module.exports = { writeBalanceSheetPdf, balanceSheetPdfBuffer };
