const PDFDocument = require('pdfkit');

const fmt = (n) => Number(n || 0).toFixed(2);

// Streams a Trial Balance report as a PDF onto the given writable stream
// (an Express response, in normal use). Kept separate from reportService so
// the report data itself stays a plain JSON-serializable object usable by
// both the JSON endpoint and this export.
function writeTrialBalancePdf(reportData, stream) {
  const doc = new PDFDocument({ margin: 40, size: 'A4', layout: 'landscape' });
  doc.pipe(stream);

  const { report, accounts, summary, generatedBy, generatedDate } = reportData;

  doc.fontSize(16).text('Accounting CRM', { align: 'center' });
  doc.fontSize(13).text('Trial Balance', { align: 'center' });
  doc.moveDown(0.5);

  doc.fontSize(9).fillColor('#444');
  const metaLine = [
    report.reportId ? `Report ID: ${report.reportId}` : null,
    report.financialYear ? `Financial Year: ${report.financialYear}` : null,
    report.reportPeriod ? `Period: ${report.reportPeriod}` : null,
    report.fromDate || report.toDate ? `Range: ${report.fromDate || '...'} to ${report.toDate || '...'}` : null,
    `Currency: ${report.currency || 'INR'}`,
    `Status: ${report.reportStatus || 'Generated'}`
  ].filter(Boolean).join('   |   ');
  doc.text(metaLine, { align: 'center' });
  doc.moveDown(1);
  doc.fillColor('#000');

  const colWidths = [70, 150, 80, 75, 75, 75, 75, 75, 75];
  const headers = ['Code', 'Account Name', 'Type', 'Opening Dr', 'Opening Cr', 'Debit', 'Credit', 'Closing Dr', 'Closing Cr'];
  let y = doc.y;
  const startX = doc.page.margins.left;

  const drawRow = (cells, opts = {}) => {
    let x = startX;
    doc.fontSize(opts.fontSize || 9).font(opts.bold ? 'Helvetica-Bold' : 'Helvetica');
    cells.forEach((cell, i) => {
      doc.text(String(cell), x, y, { width: colWidths[i], align: i <= 2 ? 'left' : 'right' });
      x += colWidths[i];
    });
    y += 18;
  };

  drawRow(headers, { bold: true });
  doc.moveTo(startX, y).lineTo(startX + colWidths.reduce((a, b) => a + b, 0), y).stroke();
  y += 4;

  accounts.forEach((row) => {
    if (y > doc.page.height - doc.page.margins.bottom - 40) {
      doc.addPage({ margin: 40, size: 'A4', layout: 'landscape' });
      y = doc.page.margins.top;
    }
    drawRow([
      row.accountCode, row.accountName, row.accountType,
      fmt(row.openingDebit), fmt(row.openingCredit),
      fmt(row.debitAmount), fmt(row.creditAmount),
      fmt(row.closingDebit), fmt(row.closingCredit)
    ]);
  });

  y += 6;
  doc.moveTo(startX, y).lineTo(startX + colWidths.reduce((a, b) => a + b, 0), y).stroke();
  y += 8;
  drawRow(['', '', '', '', '', '', '', fmt(summary.totalDebit), fmt(summary.totalCredit)], { bold: true });
  doc.fontSize(9).font('Helvetica-Bold').text('TOTAL', startX + colWidths[0] + colWidths[1], y - 18);
  y += 4;
  doc.fontSize(10).font('Helvetica-Bold').text(
    `Difference: ${fmt(summary.difference)}   |   Balance Status: ${summary.balanceStatus}`,
    startX, y
  );

  y += 30;
  doc.fontSize(8).font('Helvetica').fillColor('#666').text(
    `Generated By: ${generatedBy || '—'}   |   Generated Date: ${generatedDate ? new Date(generatedDate).toLocaleString() : '—'}`,
    startX, y
  );

  doc.end();
}

// Same PDF, collected into a Buffer instead of streamed — used for the
// email attachment (Email Report), where we need the bytes up front rather
// than piping straight to an HTTP response.
function trialBalancePdfBuffer(reportData) {
  const { PassThrough } = require('stream');
  return new Promise((resolve, reject) => {
    const stream = new PassThrough();
    const chunks = [];
    stream.on('data', (chunk) => chunks.push(chunk));
    stream.on('end', () => resolve(Buffer.concat(chunks)));
    stream.on('error', reject);
    writeTrialBalancePdf(reportData, stream);
  });
}

module.exports = { writeTrialBalancePdf, trialBalancePdfBuffer };
