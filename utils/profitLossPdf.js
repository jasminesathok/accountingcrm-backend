const PDFDocument = require('pdfkit');

const fmt = (n) => Number(n || 0).toFixed(2);

// Streams a Profit & Loss report as a PDF onto the given writable stream (an
// Express response, in normal use). Kept separate from reportService so the
// report data itself stays a plain JSON-serializable object usable by both
// the JSON endpoint and this export.
function writeProfitLossPdf(reportData, stream) {
  const doc = new PDFDocument({ margin: 40, size: 'A4' });
  doc.pipe(stream);

  const { report, income, cogs, operatingExpenses, profit, comparison, generatedBy, generatedDate } = reportData;
  const startX = doc.page.margins.left;
  const width = doc.page.width - doc.page.margins.left - doc.page.margins.right;

  doc.fontSize(16).text('Accounting CRM', { align: 'center' });
  doc.fontSize(13).text(report.reportName || 'Profit & Loss Report', { align: 'center' });
  doc.moveDown(0.5);

  doc.fontSize(9).fillColor('#444');
  const metaLine = [
    report.reportId ? `Report ID: ${report.reportId}` : null,
    report.financialYear ? `Financial Year: ${report.financialYear}` : null,
    report.reportPeriod ? `Period: ${report.reportPeriod}` : null,
    report.fromDate || report.toDate ? `Range: ${report.fromDate || '...'} to ${report.toDate || '...'}` : null,
    `Currency: ${report.currency || 'INR'}`,
    `Status: ${report.reportStatus || 'Generated'}`
  ].filter(Boolean).join('   |   ');
  doc.text(metaLine, { align: 'center' });
  doc.moveDown(1);
  doc.fillColor('#000');

  const drawSectionTitle = (title) => {
    doc.moveDown(0.5);
    doc.fontSize(11).font('Helvetica-Bold').text(title, startX);
    doc.moveTo(startX, doc.y + 2).lineTo(startX + width, doc.y + 2).stroke();
    doc.moveDown(0.5);
  };

  const drawLine = (label, value, opts = {}) => {
    doc.fontSize(opts.fontSize || 10).font(opts.bold ? 'Helvetica-Bold' : 'Helvetica');
    const y = doc.y;
    doc.text(label, startX + (opts.indent || 0), y, { width: width - 160, continued: false });
    doc.text(fmt(value), startX, y, { width, align: 'right' });
    doc.moveDown(0.2);
  };

  drawSectionTitle('Income Details');
  drawLine('Sales Revenue', income.salesRevenue);
  drawLine('Service Revenue', income.serviceRevenue);
  drawLine('Other Income', income.otherIncome);
  drawLine('Interest Income', income.interestIncome);
  drawLine('Total Income', income.totalIncome, { bold: true });

  drawSectionTitle('Cost of Goods Sold (COGS)');
  drawLine('Opening Stock', cogs.openingStock);
  drawLine('Purchases', cogs.purchases);
  drawLine('Purchase Returns', cogs.purchaseReturns);
  drawLine('Closing Stock', cogs.closingStock);
  drawLine('Cost of Goods Sold', cogs.costOfGoodsSold, { bold: true });

  drawSectionTitle('Operating Expenses');
  drawLine('Salary Expense', operatingExpenses.salaryExpense);
  drawLine('Rent Expense', operatingExpenses.rentExpense);
  drawLine('Utility Expense', operatingExpenses.utilityExpense);
  drawLine('Travel Expense', operatingExpenses.travelExpense);
  drawLine('Marketing Expense', operatingExpenses.marketingExpense);
  drawLine('Office Expense', operatingExpenses.officeExpense);
  drawLine('Depreciation', operatingExpenses.depreciation);
  drawLine('Other Expenses', operatingExpenses.otherExpenses);
  drawLine('Total Operating Expenses', operatingExpenses.totalOperatingExpenses, { bold: true });

  drawSectionTitle('Profit Calculation');
  drawLine('Gross Profit', profit.grossProfit, { bold: true });
  drawLine('Operating Profit', profit.operatingProfit, { bold: true });
  drawLine('Net Profit Before Tax', profit.netProfitBeforeTax);
  drawLine('Tax Expense', profit.taxExpense);
  drawLine('Net Profit After Tax', profit.netProfitAfterTax, { bold: true, fontSize: 12 });
  if (profit.netLoss > 0) {
    doc.fillColor('#b00020');
    drawLine('Net Loss', profit.netLoss, { bold: true });
    doc.fillColor('#000');
  }

  if (comparison && (comparison.previousPeriodProfit !== null)) {
    drawSectionTitle('Comparison Details');
    drawLine('Previous Period Profit', comparison.previousPeriodProfit);
    drawLine('Current Period Profit', comparison.currentPeriodProfit);
    drawLine('Variance Amount', comparison.varianceAmount);
    doc.fontSize(10).font('Helvetica').text(
      `Profit Growth: ${comparison.profitGrowthPercent === null ? 'N/A' : fmt(comparison.profitGrowthPercent) + '%'}`,
      startX
    );
  }

  doc.moveDown(1.5);
  doc.fontSize(8).font('Helvetica').fillColor('#666').text(
    `Generated By: ${generatedBy || '—'}   |   Generated Date: ${generatedDate ? new Date(generatedDate).toLocaleString() : '—'}`,
    startX
  );

  doc.end();
}

// Same PDF, collected into a Buffer instead of streamed — used for the
// email attachment (Email Report), where we need the bytes up front rather
// than piping straight to an HTTP response.
function profitLossPdfBuffer(reportData) {
  const { PassThrough } = require('stream');
  return new Promise((resolve, reject) => {
    const stream = new PassThrough();
    const chunks = [];
    stream.on('data', (chunk) => chunks.push(chunk));
    stream.on('end', () => resolve(Buffer.concat(chunks)));
    stream.on('error', reject);
    writeProfitLossPdf(reportData, stream);
  });
}

module.exports = { writeProfitLossPdf, profitLossPdfBuffer };
