const PDFDocument = require('pdfkit');

const fmt = (n) => Number(n || 0).toFixed(2);
const fmtDate = (d) => (d ? new Date(d).toLocaleDateString('en-IN') : '-');

// Streams a Ledger Statement as a PDF onto the given writable stream (an
// Express response, in normal use). Kept separate from ledgerService so the
// statement data itself stays a plain JSON-serializable object usable by
// both the JSON endpoint and this export — same pattern as trialBalancePdf.js.
function writeLedgerStatementPdf(statement, stream) {
  const doc = new PDFDocument({ margin: 40, size: 'A4' });
  doc.pipe(stream);

  const {
    statementId, ledger, financialYear, fromDate, toDate, currency,
    openingBalance, openingDate, openingBalanceType,
    transactions, totalDebit, totalCredit, closingBalance, closingBalanceType,
    generatedBy, generatedDate
  } = statement;

  doc.fontSize(16).text('Accounting CRM', { align: 'center' });
  doc.fontSize(13).text('Ledger Statement', { align: 'center' });
  doc.moveDown(0.5);

  doc.fontSize(9).fillColor('#444');
  const metaLine = [
    statementId ? `Statement ID: ${statementId}` : null,
    ledger?.ledgerName ? `Ledger: ${ledger.ledgerName}` : null,
    ledger?.ledgerCode ? `Code: ${ledger.ledgerCode}` : null,
    ledger?.accountType ? `Type: ${ledger.accountType}` : null,
    financialYear ? `FY: ${financialYear}` : null,
    fromDate || toDate ? `Range: ${fromDate || '...'} to ${toDate || '...'}` : null,
    `Currency: ${currency || 'INR'}`
  ].filter(Boolean).join('   |   ');
  doc.text(metaLine, { align: 'center' });
  doc.moveDown(1);
  doc.fillColor('#000');

  doc.fontSize(10).font('Helvetica-Bold').text(
    `Opening Balance: ${fmt(openingBalance)} ${openingBalanceType || ''}   (as of ${fmtDate(openingDate)})`,
    doc.page.margins.left, doc.y
  );
  doc.moveDown(0.75);

  const colWidths = [65, 75, 75, 75, 145, 65, 65, 65];
  const headers = ['Date', 'Voucher #', 'Voucher Type', 'Reference #', 'Description', 'Debit', 'Credit', 'Balance'];
  let y = doc.y;
  const startX = doc.page.margins.left;

  const drawRow = (cells, opts = {}) => {
    let x = startX;
    doc.fontSize(opts.fontSize || 8).font(opts.bold ? 'Helvetica-Bold' : 'Helvetica');
    cells.forEach((cell, i) => {
      doc.text(String(cell), x, y, { width: colWidths[i], align: i >= 5 ? 'right' : 'left' });
      x += colWidths[i];
    });
    y += 18;
  };

  drawRow(headers, { bold: true });
  doc.moveTo(startX, y).lineTo(startX + colWidths.reduce((a, b) => a + b, 0), y).stroke();
  y += 4;

  const ensureSpace = () => {
    if (y > doc.page.height - doc.page.margins.bottom - 60) {
      doc.addPage({ margin: 40, size: 'A4' });
      y = doc.page.margins.top;
    }
  };

  (transactions || []).forEach((row) => {
    ensureSpace();
    drawRow([
      fmtDate(row.date),
      row.voucherNumber || '-',
      row.voucherType || '-',
      row.referenceNumber || '-',
      String(row.description || '-').slice(0, 45),
      fmt(row.debit),
      fmt(row.credit),
      fmt(row.balance)
    ]);
  });

  if (!transactions || transactions.length === 0) {
    doc.fontSize(9).text('No ledger transactions found', startX, y);
    y += 18;
  }

  y += 6;
  ensureSpace();
  doc.moveTo(startX, y).lineTo(startX + colWidths.reduce((a, b) => a + b, 0), y).stroke();
  y += 10;

  doc.fontSize(10).font('Helvetica-Bold').text(
    `Total Debit: ${fmt(totalDebit)}   |   Total Credit: ${fmt(totalCredit)}   |   Closing Balance: ${fmt(closingBalance)} ${closingBalanceType || ''}`,
    startX, y
  );

  y += 26;
  ensureSpace();
  doc.fontSize(8).font('Helvetica').fillColor('#666').text(
    `Generated By: ${generatedBy || '—'}   |   Generated Date: ${generatedDate ? new Date(generatedDate).toLocaleString() : '—'}`,
    startX, y
  );

  doc.end();
}

// Same PDF, collected into a Buffer instead of streamed — used for the
// email attachment (Email Statement), where we need the bytes up front
// rather than piping straight to an HTTP response.
function ledgerStatementPdfBuffer(statement) {
  const { PassThrough } = require('stream');
  return new Promise((resolve, reject) => {
    const stream = new PassThrough();
    const chunks = [];
    stream.on('data', (chunk) => chunks.push(chunk));
    stream.on('end', () => resolve(Buffer.concat(chunks)));
    stream.on('error', reject);
    writeLedgerStatementPdf(statement, stream);
  });
}

module.exports = { writeLedgerStatementPdf, ledgerStatementPdfBuffer };
